# Узлы-варианты для семейства AR (подключается в ar_geo.py через exec — пользуется его box/chz/octz/bone/_by/SW).
# Координаты — «до сужения и сплющивания», как в исходной модели M416: коробка ±1.2, цевьё ±1.5, ось y=9.5.
# После построения ar_geo сужает детали по x и сплющивает по y (narrow/squash), поэтому ширины здесь заложены с запасом.


def shift_bone(bn, dz):
    if abs(dz) < 1e-9:
        return
    b = _by[bn]
    b['pivot'][2] = round(b['pivot'][2] + dz, 4)
    for c in b['cubes']:
        for k in ('f', 't', 'o'):
            if k in c:
                c[k][2] = round(c[k][2] + dz, 4)


