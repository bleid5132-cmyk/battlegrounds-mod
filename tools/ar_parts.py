def alt_handguard(style):
    if style == 'round':
        # круглое рифлёное цевьё (M16A4 / K2): две половинки, рёбра, металлический колпачок и кольцо
        octz(G, 0, BORE, 1.75, HG0, HG1, 'hg')
        z = HG0 + 0.35
        while z + 0.3 < HG1 - 0.3:
            octz(G, 0, BORE, 1.83, z, z + 0.3, 'hg_hi')
            z += 0.75
        for zz in [HG0 + 0.6 + 1.1 * i for i in range(int((HG1 - HG0 - 1.2) / 1.1))]:
            for a in (0, 180):                                                    # вентиляционные отверстия сверху и снизу
                rad = math.radians(a)
                y = BORE + math.cos(rad) * 1.78
                box(G, (-0.28, y - 0.06, zz), (0.28, y + 0.06, zz + 0.6), 'dark')
        octz(G, 0, BORE, 1.35, HG0 - 0.45, HG0, 'metal_d')                      # колпачок
        octz(G, 0, BORE, 1.95, HG1 - 0.1, HG1 + 0.35, 'metal_d')                # дельта-кольцо
        box(G, (-0.4, BORE - 0.05, HG1 - 0.1), (0.4, BORE + 0.05, HG1 + 0.35), 'metal_hi')
    elif style == 'mlok':
        # тонкое восьмигранное M-LOK цевьё (Mk47) с планкой сверху и пазами на гранях
        chz(G, -1.35, 1.35, 7.9, 11.1, HG0, HG1, 0.45, 'hg')
        chz(G, -1.42, 1.42, 7.85, 11.15, HG1 - 0.25, HG1, 0.45, 'hg_hi')
        octz(G, 0, BORE, 0.62, HG0 - 0.02, HG0, 'dark')
        pic_top(G, HG0, HG1 - 0.2, 12.1)
        z = HG0 + 0.6
        while z + 1.1 < HG1 - 0.5:
            for (x, y, rz) in ((1.35, 9.5, 0), (-1.35, 9.5, 0), (0.0, 7.9, 0)):
                if rz == 0 and abs(x) > 0:
                    box(G, (x - 0.03, y - 0.25, z), (x + 0.03, y + 0.25, z + 1.0), 'dark')
                else:
                    box(G, (x - 0.3, y - 0.03, z), (x + 0.3, y + 0.03, z + 1.0), 'dark')
            for (x, y, rz) in ((1.05, 10.8, -45), (-1.05, 10.8, 45), (1.05, 8.2, 45), (-1.05, 8.2, -45)):
                box(G, (x - 0.22, y - 0.04, z + 0.2), (x + 0.22, y + 0.04, z + 0.8), 'dark', (0, 0, rz), (x, y, z + 0.5))
            z += 1.6
    elif style == 'scar':
        # SCAR: монолитная верхняя часть с планкой на всю длину, снизу полимерное цевьё, короткие боковые планки
        chz(G, -1.45, 1.45, 8.75, 11.35, HG0, HG1 + 0.05, 0.3, 'rec')
        pic_top(G, HG0, HG1 + 0.05, 12.1)
        chz(G, -1.3, 1.3, 7.3, 8.9, HG0 + 0.2, HG1, 0.4, 'poly')
        for z in [HG0 + 1.0 + 1.2 * i for i in range(int((HG1 - HG0 - 2) / 1.2))]:
            box(G, (1.3, 7.7, z), (1.34, 8.5, z + 0.7), 'poly_hi')
            box(G, (-1.34, 7.7, z), (-1.3, 8.5, z + 0.7), 'poly_hi')
        pic_side(G, 1, HG0 + 0.3, HG0 + 3.5, 10.0)
        pic_side(G, -1, HG0 + 0.3, HG0 + 3.5, 10.0)
        pic_bottom(G, HG0 + 0.4, HG0 + 3.6, 7.3)
        octz(G, 0, BORE, 0.62, HG0 - 0.02, HG0, 'dark')
        for z in (HG0 + 4.5, HG0 + 6.0):                                         # винты
            octx(G, 10.0, z, 0.16, 1.45, 1.52, 'metal')
            octx(G, 10.0, z, 0.16, -1.52, -1.45, 'metal')
    elif style == 'g36':
        # G36C: полимерное цевьё с рядами отверстий, планки сверху и снизу
        chz(G, -1.4, 1.4, 7.5, 10.9, HG0, HG1, 0.5, 'hg')
        pic_top(G, HG0, HG1 - 0.2, 12.1)
        cx(G, 2.2, 10.9, 11.4, HG0, HG1, 'hg')
        pic_bottom(G, HG0 + 0.6, HG0 + 4.0, 7.5)
        for z in [HG0 + 0.8 + 0.9 * i for i in range(int((HG1 - HG0 - 1.6) / 0.9))]:
            for y in (8.4, 9.6):
                box(G, (1.38, y, z), (1.42, y + 0.55, z + 0.5), 'dark')
                box(G, (-1.42, y, z), (-1.38, y + 0.55, z + 0.5), 'dark')
        octz(G, 0, BORE, 0.62, HG0 - 0.02, HG0, 'dark')


