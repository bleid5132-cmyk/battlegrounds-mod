def retime(anim, k):
    """Растянуть анимацию по времени в k раз."""
    a = copy.deepcopy(anim)
    a['length'] = round(a['length'] * k, 4)
    for bone in a['bones'].values():
        for chan in bone.values():
            for key in chan:
                key[0] = round(key[0] * k, 4)
    if 'sounds' in a:
        for s in a['sounds']:
            s[0] = round(s[0] * k, 4)
    return a


def scale_values(anim, k):
    a = copy.deepcopy(anim)
    for bone in a['bones'].values():
        for chan in bone.values():
            for key in chan:
                key[1:4] = [round(v * k, 4) for v in key[1:4]]
    return a


