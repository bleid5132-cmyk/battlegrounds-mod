def _look(m, up):
    """Эйлеры корня: ствол смотрит в m, верх оружия ближе к up (пространство камеры)."""
    z = -_np.array(m, float); z /= _np.linalg.norm(z)
    y = _np.array(up, float); y -= y.dot(z) * z; y /= _np.linalg.norm(y)
    x = _np.cross(y, z)
    return [round(v, 2) for v in _E(_np.column_stack([x, y, z]))]


